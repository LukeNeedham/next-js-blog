import fs from 'node:fs/promises'
import path from 'node:path'
import type { Fields } from './fields'
import { fetchContent } from './fetchContent'
import { parseArticle } from './parseArticle'
import { renderMarkdown } from './renderMarkdown'
import { siteImages } from './rewriteImages'

export interface BuildBlogOptions {
  /** The repo holding the content, `owner/name`: `articles/*.md` and `images/*` */
  contentRepo: string
  /** The front matter every article must have, by field name */
  fields: Fields
  /** The CSS of an article (see `chakraToCss`), written next to the generated articles */
  articleCss: string
  /** The root of the site: where `src/generated`, `public/blog-images` and `content` are. The current folder by default */
  root?: string
}

async function exists(file: string): Promise<boolean> {
  return fs.access(file).then(
    () => true,
    () => false,
  )
}

/**
 * BUILD TIME ONLY. Downloads the blog content (see `fetchContent`), checks and renders each markdown article to HTML,
 * lists the articles from their front matter, copies the images to `public/blog-images` and writes the article CSS.
 * The articles, their HTML and the CSS are written to `src/generated`, which is all that the app has to import.
 */
export async function buildBlog(options: BuildBlogOptions): Promise<void> {
  const root = path.resolve(options.root ?? process.cwd())
  const outDir = path.join(root, 'src', 'generated')
  const publicImagesDir = path.join(root, 'public', 'blog-images')

  const content = await fetchContent(root, options.contentRepo)
  const articlesDir = path.join(content, 'articles')
  const imagesDir = path.join(content, 'images')
  await fs.mkdir(outDir, { recursive: true })

  // The images are served by the site, from `public/blog-images`
  await fs.rm(publicImagesDir, { recursive: true, force: true })
  await fs.mkdir(publicImagesDir, { recursive: true })
  if (await exists(imagesDir)) {
    await fs.cp(imagesDir, publicImagesDir, { recursive: true })
  }

  // The article id is the markdown file name
  const files = (await fs.readdir(articlesDir)).filter((it) => it.endsWith('.md')).sort()
  const html: Record<string, string> = {}
  const articles: Record<string, string>[] = []
  for (const file of files) {
    const id = path.basename(file, '.md')
    const { meta, body } = parseArticle(
      id,
      await fs.readFile(path.join(articlesDir, file), 'utf-8'),
      options.fields,
    )
    for (const [name, type] of Object.entries(options.fields)) {
      if (type === 'image') {
        if (!(await exists(path.join(imagesDir, meta[name])))) {
          throw new Error(
            `articles/${id}.md: '${name}' is '${meta[name]}', which is not in images.`,
          )
        }
        meta[name] = siteImages + meta[name]
      }
    }
    articles.push({ id, ...meta })
    html[id] = await renderMarkdown(body)
  }
  await fs.writeFile(path.join(outDir, 'blog-articles.json'), JSON.stringify(articles, null, 2))
  await fs.writeFile(path.join(outDir, 'blog-html.json'), JSON.stringify(html, null, 2))

  const banner =
    '/* GENERATED by next-js-blog-build from the styling of the site. Do not edit. */\n\n'
  await fs.writeFile(path.join(outDir, 'blog-article.css'), banner + options.articleCss)

  console.log(
    `Generated ${files.length} blog articles and article CSS in ${path.relative(root, outDir)}`,
  )
}
